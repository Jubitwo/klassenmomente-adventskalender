import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const defaults = JSON.parse(await readFile(new URL('calendar-data.json', root), 'utf8'));
globalThis.location = { href: 'https://example.org/calendar/' };
const moduleURL = source => `data:text/javascript;base64,${Buffer.from(source).toString('base64')}`;
const storage = moduleURL(await readFile(new URL('storage.js', root), 'utf8'));
const source = (await readFile(new URL('github.js', root), 'utf8')).replace("'./storage.js'", JSON.stringify(storage));
const { GitHubPublisher } = await import(moduleURL(source));
const sha = 'a'.repeat(40);
const nextSha = 'b'.repeat(40);
const metadata = { sha, type: 'file', size: 8000 };
const file = { ...metadata, encoding: 'base64', content: Buffer.from(JSON.stringify(defaults)).toString('base64') };
let requests = [];
let replies = [];
globalThis.fetch = async (url, options) => {
  requests.push({ url, options });
  const reply = replies.shift();
  if (!reply) throw new Error('Unexpected request');
  if (reply instanceof Error) throw reply;
  return { ok: !reply.status || reply.status < 400, status: reply.status || 200, json: async () => structuredClone(reply.data ?? reply) };
};
const token = 'test_token_not_a_real_credential';
let checks = 0;
function check(fn) { fn(); checks++; }
async function asyncCheck(fn) { await fn(); checks++; }
const publisher = new GitHubPublisher();
check(() => assert.equal(publisher.connected, false));
await asyncCheck(() => assert.rejects(() => publisher.publish(defaults), /verbinden/));
await asyncCheck(() => assert.rejects(() => publisher.connect('bad'), /gültiges/));
replies = [file];
await publisher.connect(token);
check(() => assert.equal(publisher.connected, true));
check(() => assert.equal(requests[0].options.headers.Authorization, `Bearer ${token}`));
check(() => assert.equal(requests[0].options.headers.Accept, 'application/vnd.github.object+json'));
check(() => assert.equal(requests[0].url.includes(token), false));
replies = [metadata, { content: { sha: nextSha }, commit: { sha: nextSha } }];
const url = await publisher.publish(defaults);
check(() => assert.equal(url, `https://github.com/Jubitwo/klassenmomente-adventskalender/commit/${nextSha}`));
const put = requests.at(-1);
const body = JSON.parse(put.options.body);
check(() => assert.equal(put.options.method, 'PUT'));
check(() => assert.equal(body.sha, sha));
check(() => assert.equal(body.branch, 'main'));
check(() => assert.equal(put.options.body.includes(token), false));
check(() => assert.equal(JSON.parse(Buffer.from(body.content, 'base64').toString('utf8')).doors[5].title, defaults.doors[5].title));
check(() => assert.equal(JSON.parse(Buffer.from(body.content, 'base64').toString('utf8')).doors[5].task, defaults.doors[5].task));
replies = [{ ...metadata, sha: nextSha }, { content: { sha }, commit: { sha } }];
await asyncCheck(() => publisher.publish(defaults));
const count = requests.length;
replies = [{ ...metadata, sha: nextSha }];
await asyncCheck(() => assert.rejects(() => publisher.publish(defaults), /Konflikt/));
check(() => assert.equal(requests.length, count + 1));
replies = [file];
await asyncCheck(async () => assert.equal((await publisher.loadCalendar()).year, defaults.year));
replies = [metadata, { encoding: 'base64', content: file.content }];
await asyncCheck(async () => assert.equal((await publisher.loadCalendar()).doors.length, 24));
check(() => assert.equal(requests.at(-1).url.endsWith(`/git/blobs/${sha}`), true));
replies = [metadata, { status: 409 }];
await asyncCheck(() => assert.rejects(() => publisher.publish(defaults), /Konflikt/));
check(() => assert.equal(requests.at(-1).options.method, 'PUT'));
replies = [metadata, new Error('timeout after commit')];
await asyncCheck(() => assert.rejects(() => publisher.publish(defaults), /bereits erfolgt/));
await asyncCheck(() => assert.rejects(() => publisher.publish({ ...defaults, year: '2026' })));
const large = structuredClone(defaults);
for (const door of large.doors.slice(0, 6)) door.image = `data:image/png;base64,${'A'.repeat(1490000)}`;
await asyncCheck(() => assert.rejects(() => publisher.publish(large), /8 MB/));
for (const status of [401, 403, 404, 409, 422, 500]) {
  replies = [{ status }];
  await asyncCheck(() => assert.rejects(() => publisher.connect(token)));
  check(() => assert.equal(publisher.connected, false));
}
replies = [new Error('network')];
await asyncCheck(() => assert.rejects(() => publisher.connect(token), /nicht erreichbar/));
replies = [{ ...file, size: 9 * 1024 * 1024 }];
await asyncCheck(() => assert.rejects(() => publisher.connect(token), /8 MB/));
replies = [{ ...file, content: Buffer.from('{}').toString('base64') }];
await asyncCheck(() => assert.rejects(() => publisher.connect(token)));
replies = [file];
await publisher.connect(token);
publisher.disconnect();
check(() => assert.equal(publisher.connected, false));
await asyncCheck(() => assert.rejects(() => publisher.loadCalendar(), /verbinden/));
let finish;
globalThis.fetch = () => new Promise(resolve => { finish = () => resolve({ ok: true, json: async () => file }); });
const connecting = publisher.connect(token);
publisher.disconnect();
finish();
await asyncCheck(() => assert.rejects(() => connecting, /beendet/));
check(() => assert.equal(publisher.connected, false));
console.log(`${checks} GitHub-Prüfungen erfolgreich: UTF-8, Commit, Konflikte, große Dateien, Token-Lebensdauer und API-Fehler.`);
